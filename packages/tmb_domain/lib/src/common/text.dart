/// Нормализация текста, которую читатель обязан выполнять до валидации и
/// хеширования (SCHEMAS §0): `\r\n`/`\r` → `\n`, затем NFC.
library;

/// Заменяет `\r\n` и одиночный `\r` на `\n`.
String normalizeNewlines(String s) {
  if (!s.contains('\r')) return s;
  return s.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
}

/// Приводит строку к NFC.
///
/// ОГРАНИЧЕНИЕ. В чистом Dart нет `String.normalize`, а таблицы Unicode в
/// домен тащить не хочется (ноль зависимостей, ноль расхождений между VM и
/// вебом). Поэтому:
///  * строка без комбинируемых знаков (ASCII, кириллица, включая `і ї є ґ`,
///    латиница с предкомпонованными буквами) возвращается как есть — для неё
///    NFC тождественна;
///  * строка с комбинируемыми знаками (U+0300–U+036F, а также блоки
///    U+1AB0–U+1AFF, U+1DC0–U+1DFF, U+20D0–U+20FF, U+FE20–U+FE2F) — это
///    потенциально НЕ-NFC, привести её мы не умеем: бросается
///    [UnsupportedError];
///  * остаточная дыра: символы-синглеты с каноническим разложением
///    (например U+212B ANGSTROM SIGN, U+2126 OHM SIGN) и разложенный хангыль
///    проходят без изменений. В контенте пака их быть не должно; поймать их —
///    задача валидатора, а не этого слоя.
///
/// Когда контент с комбинируемыми знаками понадобится (вьетнамский, греческая
/// политоника), здесь нужна полноценная реализация NFC, а не обход.
String nfc(String s) {
  for (var i = 0; i < s.length; i++) {
    final c = s.codeUnitAt(i);
    // Быстрый путь: всё ниже U+0300 комбинируемым знаком быть не может.
    if (c < 0x0300) continue;
    if (_isCombining(c)) {
      throw UnsupportedError(
        'NFC-нормализация строк с комбинируемыми знаками (U+'
        '${c.toRadixString(16).toUpperCase().padLeft(4, '0')}) не реализована '
        'в tmb_domain; используйте предкомпонованные символы.',
      );
    }
  }
  return s;
}

bool _isCombining(int c) =>
    (c >= 0x0300 && c <= 0x036F) ||
    (c >= 0x1AB0 && c <= 0x1AFF) ||
    (c >= 0x1DC0 && c <= 0x1DFF) ||
    (c >= 0x20D0 && c <= 0x20FF) ||
    (c >= 0xFE20 && c <= 0xFE2F);

/// Полная нормализация читателя: переводы строк, затем NFC.
String normalizeText(String s) => nfc(normalizeNewlines(s));
